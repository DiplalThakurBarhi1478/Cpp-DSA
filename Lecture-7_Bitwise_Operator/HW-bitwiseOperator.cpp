#include<iostream>

using namespace std;

int main(){

    cout << "Bitwise Operators" << endl;
    
    cout << "10 & 6 : " << (10 & 6) << endl;
    cout << "10 | 6 : " << (10 | 6) << endl;
    cout << "10 ^ 6 : " << (10 ^ 6) << endl;
    cout << "10 << 2: " << (10 << 2) << endl;
    cout << "10 >> 1: " << (10 >> 1) << endl;

    return 0;

}